import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(scriptDir, '..')
const tokenPath = path.join(rootDir, 'src/design-system/tokens/pangchong.tokens.json')
const cssPath = path.join(rootDir, 'src/design-system/tokens/tokens.css')
const publicCssPath = path.join(rootDir, 'public/design-system.tokens.css')
const tailwindPath = path.join(rootDir, 'src/design-system/tokens/tailwind-theme.js')
const checkOnly = process.argv.includes('--check')

const tokens = JSON.parse(await readFile(tokenPath, 'utf8'))

function kebab(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .toLowerCase()
}

function flatten(node, segments = [], output = []) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue
    const next = [...segments, key]
    if (value && typeof value === 'object' && '$value' in value) {
      output.push({
        path: next,
        name: `--pc-${next.map(kebab).join('-')}`,
        type: value.$type,
        value: value.$value,
        description: value.$description || '',
      })
      continue
    }
    if (value && typeof value === 'object') flatten(value, next, output)
  }
  return output
}

function cssValue(value) {
  if (typeof value !== 'string') return String(value)
  const reference = value.match(/^\{(.+)\}$/)
  if (reference) return `var(--pc-${reference[1].split('.').map(kebab).join('-')})`
  return value
}

function hexToRgb(value) {
  const match = value.match(/^#([0-9a-f]{6})$/i)
  if (!match) return null
  const integer = Number.parseInt(match[1], 16)
  return `${(integer >> 16) & 255} ${(integer >> 8) & 255} ${integer & 255}`
}

const flatTokens = flatten(tokens)
const cssLines = [
  '/* Generated by scripts/build-design-tokens.mjs. Do not edit directly. */',
  ':root {',
]

for (const token of flatTokens) {
  if (token.description) cssLines.push(`  /* ${token.description} */`)
  cssLines.push(`  ${token.name}: ${cssValue(token.value)};`)
  if (token.type === 'color') {
    const rgb = hexToRgb(token.value)
    if (rgb) cssLines.push(`  ${token.name}-rgb: ${rgb};`)
  }
}

cssLines.push('}', '')
cssLines.push(
  "[data-theme='high-contrast'] {",
  '  --pc-color-semantic-text-secondary: var(--pc-color-dark-100);',
  '  --pc-color-semantic-text-muted: var(--pc-color-dark-200);',
  '  --pc-color-semantic-border-subtle: var(--pc-color-dark-600);',
  '}',
  '',
  '@media (prefers-reduced-motion: reduce) {',
  '  :root {',
    '    --pc-motion-duration-fast: 1ms;',
    '    --pc-motion-duration-micro: 1ms;',
    '    --pc-motion-duration-normal: 1ms;',
    '    --pc-motion-duration-slow: 1ms;',
    '    --pc-motion-duration-prominent: 1ms;',
    '    --pc-motion-duration-ambient: 1ms;',
    '    --pc-motion-duration-spin: 1ms;',
    '    --pc-motion-duration-loading: 1ms;',
    '    --pc-motion-duration-shimmer: 1ms;',
  '  }',
  '}',
  ''
)

const palette = (name) => Object.fromEntries(
  Object.keys(tokens.color[name]).map((shade) => [
    shade,
    `rgb(var(--pc-color-${name}-${shade}-rgb) / <alpha-value>)`,
  ])
)

const tailwindSource = `/* Generated by scripts/build-design-tokens.mjs. Do not edit directly. */
export const pangchongTailwindTheme = ${JSON.stringify({
  colors: {
    primary: palette('brand'),
    dark: palette('dark'),
  },
  fontFamily: {
    sans: ['Noto Sans SC', '-apple-system', 'BlinkMacSystemFont', 'Segoe UI', 'sans-serif'],
    mono: ['SFMono-Regular', 'Consolas', 'Liberation Mono', 'monospace'],
  },
  borderRadius: {
    sm: 'var(--pc-radius-sm)',
    md: 'var(--pc-radius-md)',
    lg: 'var(--pc-radius-lg)',
    xl: 'var(--pc-radius-xl)',
  },
  boxShadow: {
    'ds-sm': 'var(--pc-shadow-sm)',
    'ds-md': 'var(--pc-shadow-md)',
    'ds-lg': 'var(--pc-shadow-lg)',
  },
}, null, 2)}

export default pangchongTailwindTheme
`

async function ensureCurrent(targetPath, expected) {
  if (!checkOnly) {
    await writeFile(targetPath, expected, 'utf8')
    return
  }
  const current = await readFile(targetPath, 'utf8').catch(() => '')
  if (current !== expected) {
    console.error(`Design token output is stale: ${path.relative(rootDir, targetPath)}`)
    process.exitCode = 1
  }
}

await ensureCurrent(cssPath, `${cssLines.join('\n')}`)
await ensureCurrent(publicCssPath, `${cssLines.join('\n')}`)
await ensureCurrent(tailwindPath, tailwindSource)

if (!process.exitCode) {
  console.log(checkOnly ? 'Design token outputs are current.' : `Generated ${flatTokens.length} design tokens.`)
}
