"""
胖虫电脑 - DIY八大件产品数据库
运行: python diy_parts.py
输出: 写入 pangchong.db 的 diy_parts 表

八大件分类:
  cpu       处理器
  gpu       显卡
  motherboard 主板
  ram       内存
  ssd       固态硬盘
  psu       电源
  case      机箱
  cooler    散热器
"""

import sqlite3
import json
from datetime import datetime
from pathlib import Path

DB_PATH = Path(__file__).parent / "pangchong.db"


def init_diy_table(conn):
    conn.execute("""
        CREATE TABLE IF NOT EXISTS diy_parts (
            id              TEXT PRIMARY KEY,
            category        TEXT NOT NULL,
            brand           TEXT NOT NULL,
            name            TEXT NOT NULL,
            model           TEXT,
            spec            TEXT,
            ref_price       REAL,
            cost_price      REAL,
            tier            TEXT,
            platform        TEXT,
            socket          TEXT,
            chipset         TEXT,
            spec_json       TEXT,
            in_stock        INTEGER DEFAULT 1,
            recommend       INTEGER DEFAULT 0,
            notes           TEXT,
            created_at      TEXT NOT NULL,
            updated_at      TEXT NOT NULL
        )
    """)
    conn.execute("CREATE INDEX IF NOT EXISTS idx_diy_cat ON diy_parts(category)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_diy_brand ON diy_parts(brand)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_diy_tier ON diy_parts(tier)")
    conn.commit()


def insert_part(conn, p):
    now = datetime.now().isoformat()
    conn.execute("""
        INSERT OR REPLACE INTO diy_parts
        (id, category, brand, name, model, spec, ref_price, cost_price,
         tier, platform, socket, chipset, spec_json, in_stock, recommend, notes, created_at, updated_at)
        VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
    """, (
        p["id"], p["category"], p["brand"], p["name"], p.get("model", ""),
        p.get("spec", ""), p.get("ref_price", 0), p.get("cost_price"),
        p.get("tier", ""), p.get("platform", ""), p.get("socket", ""),
        p.get("chipset", ""), json.dumps(p.get("spec_detail", {}), ensure_ascii=False),
        p.get("in_stock", 1), p.get("recommend", 0), p.get("notes", ""),
        now, now,
    ))


def build_database():
    conn = sqlite3.connect(str(DB_PATH))
    init_diy_table(conn)

    parts = []
    parts.extend(get_cpus())
    parts.extend(get_gpus())
    parts.extend(get_motherboards())
    parts.extend(get_ram())
    parts.extend(get_ssds())
    parts.extend(get_psus())
    parts.extend(get_cases())
    parts.extend(get_coolers())

    for p in parts:
        insert_part(conn, p)

    conn.commit()

    # 打印摘要
    print(f"\n  DIY八大件数据库已建立")
    print(f"  数据库: {DB_PATH}")
    print(f"  总计: {len(parts)} 个配件\n")

    cats = {}
    for p in parts:
        cats.setdefault(p["category"], []).append(p)

    cat_names = {
        "cpu": "处理器 CPU", "gpu": "显卡 GPU", "motherboard": "主板 Motherboard",
        "ram": "内存 RAM", "ssd": "固态硬盘 SSD", "psu": "电源 PSU",
        "case": "机箱 Case", "cooler": "散热器 Cooler",
    }
    for cat, items in cats.items():
        brands = set(i["brand"] for i in items)
        prices = [i["ref_price"] for i in items if i.get("ref_price")]
        print(f"  {cat_names.get(cat, cat)}: {len(items)} 款 ({'/'.join(brands)}) "
              f"RMB {min(prices):,.0f} - {max(prices):,.0f}")

    conn.close()
    print()


